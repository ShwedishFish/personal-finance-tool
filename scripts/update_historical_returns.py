"""Regenerate backend/app/finance/historical_data.py from Aswath Damodaran's annual returns workbook.

Usage:
    curl -sSLo /tmp/histretSP.xls https://www.stern.nyu.edu/~adamodar/pc/datasets/histretSP.xls
    pip install xlrd
    python scripts/update_historical_returns.py /tmp/histretSP.xls
"""

import sys
from pathlib import Path

import xlrd

OUT = Path(__file__).resolve().parent.parent / "backend" / "app" / "finance" / "historical_data.py"
SHEET = "Nominal vs Real Data"


def main(path: str) -> None:
    sheet = xlrd.open_workbook(path).sheet_by_name(SHEET)
    rows = []
    for r in range(1, sheet.nrows):
        year, stocks, _bills, bonds, inflation = (sheet.cell_value(r, c) for c in range(5))
        if not isinstance(year, float) or not all(isinstance(v, float) for v in (stocks, bonds, inflation)):
            continue
        rows.append(f"    ({int(year)}, {stocks:.6f}, {bonds:.6f}, {inflation:.6f}),")
    OUT.write_text(
        '"""US annual returns, generated by scripts/update_historical_returns.py. Do not edit by hand.\n\n'
        "Source: Aswath Damodaran, Historical Returns on Stocks, Bonds and Bills (NYU Stern),\n"
        "https://pages.stern.nyu.edu/~adamodar/New_Home_Page/datafile/histretSP.html\n"
        "Columns: year, S&P 500 total return, 10-year US Treasury total return, CPI inflation (nominal).\n"
        '"""\n\n'
        "ANNUAL_RETURNS: tuple[tuple[int, float, float, float], ...] = (\n" + "\n".join(rows) + "\n)\n"
    )
    print(f"wrote {len(rows)} years to {OUT}")


if __name__ == "__main__":
    main(sys.argv[1])
